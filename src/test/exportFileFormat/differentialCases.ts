/** Every combination of the three switches of `saveJsonToFile`, in a fixed order. */
export const OPTION_COMBINATIONS: SaveJsonOptions[] = [true, false].flatMap(
  (includeMeta) =>
    [false, true].flatMap((keepRev) =>
      [false, true].map((keepModifiedProperties) => ({
        includeMeta,
        keepRev,
        keepModifiedProperties,
      }))
    )
);

/**
 * The id of a combination of switches: `meta+rev+mod`, with a `-` for a switch that is off.
 * @param {SaveJsonOptions} options the switches
 * @returns {string} the id
 */
export function combinationId(options: SaveJsonOptions): string {
  return [
    options.includeMeta ? 'meta' : '-',
    options.keepRev ? 'rev' : '-',
    options.keepModifiedProperties ? 'mod' : '-',
  ].join('+');
}

