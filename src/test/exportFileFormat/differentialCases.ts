const NUMBER_POOL = [0, 1, -1, 42, 3.14, -0.5, 1e21, 1e-7, 123456789012];

/**
 * A random scalar: a string, a number, a boolean or null.
 * @param {() => number} random the generator
 * @returns {unknown} the value
 */
function randomScalar(random: () => number): unknown {
  const pick = random();
  if (pick < 0.5) return STRING_POOL[Math.floor(random() * STRING_POOL.length)];
  if (pick < 0.75)
    return NUMBER_POOL[Math.floor(random() * NUMBER_POOL.length)];
  if (pick < 0.85) return true;
  if (pick < 0.95) return false;
  return null;
}

/**
 * A random value: a scalar, an array or an object, nested at most `depth` levels.
 * @param {() => number} random the generator
 * @param {number} depth how many levels may still be added
 * @returns {unknown} the value
 */
function randomValue(random: () => number, depth: number): unknown {
  if (depth <= 0 || random() < 0.35) return randomScalar(random);
  if (random() < 0.3) {
    const length = Math.floor(random() * 4);
    return Array.from({ length }, () => randomValue(random, depth - 1));
  }
  return randomObject(random, depth - 1);
}

/**
 * A random object: two to four keys of the key pool, in the order the generator picks them.
 * @param {() => number} random the generator
 * @param {number} depth how many levels may still be added below it
 * @returns {Record<string, unknown>} the object
 */
function randomObject(
  random: () => number,
  depth: number
): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  const count = 2 + Math.floor(random() * 3);
  for (let i = 0; i < count; i++) {
    const key = KEY_POOL[Math.floor(random() * KEY_POOL.length)];
    result[key] = randomValue(random, depth);
  }
  return result;
}

/**
 * An object that holds `key` at the given depth: `{ id, a: { id, b: { id, <key> } } }` for depth 3.
 * @param {string} key the key
 * @param {number} depth the depth (1 is the top level)
 * @returns {object} the object
 */
function withKeyAtDepth(key: string, depth: number): object {
  let inner: Record<string, unknown> = {
    zebra: 1,
    [key]: `value of ${key}`,
    apple: { [key]: { nested: [key] }, keep: true },
  };
  for (let level = depth - 1; level >= 1; level--) {
    inner = { _id: `level-${level}`, [`child${level}`]: inner, aaa: level };
  }
  return inner;
}

