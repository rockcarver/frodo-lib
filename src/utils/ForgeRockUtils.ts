/**
 * Get new name when names collide
 * @param {string} name to apply policy to
 * @returns {string} new name according to policy
 */
export function applyNameCollisionPolicy(name: string): string {
  const capturingRegex = /(.* - imported) \(([0-9]+)\)/;
  const found = name.match(capturingRegex);
  if (found && found.length > 0 && found.length === 3) {
    // already renamed one or more times
    // return the next number
    return `${found[1]} (${parseInt(found[2], 10) + 1})`;
  }
  // first time
  return `${name} - imported (1)`;
}

/**
 * Gets the list of realms to be used for exports in special format.
 * e.g. if the realm is normally '/first/second', then it will return 'root-first-second'.
 */
export async function getRealmsForExport({
  state,
}: {
  state: State;
}): Promise<string[]> {
  return (await getRealms({ state })).map((r) => {
    const names = ['root'];
    if (r.parentPath)
      names.push(
        ...`${r.parentPath}/${r.name}`
          .replaceAll('-', '--')
          .split('/')
          .filter(Boolean)
      );
    return names.join('-');
  });
}

/**
 * Tells whether an export would request the root realm of an Identity Cloud tenant only because the tenant lists it.
 * A full export asks for every realm a deployment lists. On Identity Cloud the root realm is managed by Ping and
 * answers 403 to nearly everything: every `/realm-config/...` entity and the scripts, in every recording of a cloud
 * tenant (none of them was ever answered with 200). Only its authorization config (policies, policy sets, resource
 * types and their definitions) can be read. A caller that names the root realm itself (`onlyRealm` with the active
 * realm `/`) is not covered: the realm is requested as before.
 * @param {string} realm the realm in state format (e.g. '/' or '/alpha')
 * @param {boolean} onlyRealm true if the export is limited to the active realm
 * @param {State} state the library state
 * @returns {boolean} true if requests that Identity Cloud denies in the root realm should be skipped
 */
export function skipsDeniedRootRealmRequests({
  realm,
  onlyRealm,
  state,
}: {
  realm: string;
  onlyRealm: boolean;
  state: State;
}): boolean {
  return (
    state.getDeploymentType() === Constants.CLOUD_DEPLOYMENT_TYPE_KEY &&
    realm === '/' &&
    !onlyRealm
  );
}

/**
 * Helper that gets the normal realm name from the realm export format.
 * It reverses the format generated by getRealmsForExport.
 * e.g. if the realm is 'root-first-second', then it will return '/first/second'.
 * @param realm realm in export format
 */
export function getRealmUsingExportFormat(realm: string): string {
  return realm === 'root'
    ? '/'
    : realm.replace(/^root-|--|-/g, (m) => (m === '--' ? '-' : '/'));
}

/**
 * Helper function to get the config path required for the API call considering if the request
 * should obtain the realm config or the global config of the service in question
 * @param {boolean} globalConfig true if the global service is the target of the operation, false otherwise.
 * @returns {string} The config path to be used for the request
 */
export function getConfigPath(globalConfig: boolean): string {
  if (globalConfig) return 'global-config';
  return 'realm-config';
}

/**
 * Helper function to get the realm path required for the API call considering if the request
 * should obtain the realm config or the global config of the service in question
 * @param {boolean} globalConfig true if the global service is the target of the operation, false otherwise.
 * @returns {string} The realm path to be used for the request
 */
export function getRealmPathGlobal(
  globalConfig: boolean,
  state: State
): string {
  if (globalConfig) return '';
  return getCurrentRealmPath(state);
}

/**
 * Get realm path
 * @param {string} realm realm
 * @returns {string} a CREST-compliant realm path, e.g. /realms/root/realms/alpha
 */
export function getRealmPath(realm: string): string {
  if (!realm) realm = '/';
  if (realm.startsWith('/')) {
    realm = realm.substring(1);
  }
  const elements = ['root'].concat(
    realm.split('/').filter((element) => element !== '')
  );
  const realmPath = `/realms/${elements.join('/realms/')}`;
  return realmPath;
}

/**
 * Get current realm path
 * @returns {string} a CREST-compliant realm path, e.g. /realms/root/realms/alpha
 */
export function getCurrentRealmPath(state: State): string {
  return getRealmPath(state.getRealm());
}

/**
 * Get current realm name
 * @returns {string} name of the current realm. /alpha -> alpha
 */
export function getCurrentRealmName(state: State): string {
  const realm = state.getRealm();
  const components = realm.split('/');
  let realmName = '/';
  if (components.length > 0 && realmName !== realm) {
    realmName = components[components.length - 1];
  }
  return realmName;
}

/**
 * Get the name of the managed user object for the current realm
 * @returns {string} the name of the managed user object for the current realm
 */
export function getCurrentRealmManagedUser({
  state,
}: {
  state: State;
}): string {
  let realmManagedUser = 'user';
  if (
    state.getDeploymentType() === Constants.CLOUD_DEPLOYMENT_TYPE_KEY ||
    (state.getUseRealmPrefixOnManagedObjects() === true &&
      getCurrentRealmName(state) !== '/')
  ) {
    realmManagedUser = `${getCurrentRealmName(state)}_user`;
    debugMessage({
      message: `DeploymentType === cloud or UseRealmPrefixOnManagedObjects is true, returning '${realmManagedUser}'`,
      state: state,
    });
  }
  return realmManagedUser;
}

/**
 * Get current realm name
 * @param {string} realm realm
 * @returns {string} name of the realm. /alpha -> alpha
 */
export function getRealmName(realm: string): string {
  const components = realm.split('/');
  let realmName = '/';
  if (components.length > 0 && realmName !== realm) {
    realmName = components[components.length - 1];
  }
  return realmName;
}

/**
 * Get host-only URL without path and query params
 * @param {string} url URL with path and query params
 * @returns {string} AM host URL without path and query params
 */
export function getHostOnlyUrl(url: string): string {
  const parsedUrl = new URL(url);
  return `${parsedUrl.protocol}//${parsedUrl.host}`;
}

/**
 * Get IDM base URL
 * @param {State} state State object
 * @returns {string} IDM host URL without path and query params
 */
export function getIdmBaseUrl(state: State): string {
  if (state.getIdmHost()) {
    return state.getIdmHost();
  }
  return `${getHostOnlyUrl(state.getHost())}/openidm`;
}

/**
 * Initiate an update and optionally wait for it to complete.
 * @param {() => Promise<any>} initiateUpdate Function that initiates the update.
 * @param {() => Promise<WaitCompleted>} isComplete Function that checks the update's completion and error status.
 * @param {string} initialMessage Initial message for the progress indicator.
 * @param {string} noWaitSuccessMessage Success message when not waiting for completion.
 * @param {(isCompleted: WaitCompleted, runtime: number) => string} updateMessage Function that generates progress messages during polling.
 * @param {(isCompleted: WaitCompleted, runtime: number) => string} waitSuccessMessage Function that generates the completion message.
 * @param {(isCompleted: WaitCompleted, runtime: number) => string} timeoutMessage Function that generates the timeout message.
 * @param {(isCompleted: WaitCompleted, runtime: number) => string} errorMessage Function that generates the error message when the update reports an error.
 * @param {boolean} wait Whether to wait for the update to complete (default: false).
 * @param {number} timeout Maximum waiting time in milliseconds (default: 600000).
 * @param {number} pollInterval Time between status checks in milliseconds (default: 5000).
 * @param {number} maxConsecutiveWaitErrors Maximum consecutive polling errors allowed (default: 3).
 * @param {State} state The library state.
 * @returns {Promise<boolean>} True if initiated successfully and, when waiting, completed without errors or timeout; false otherwise.
 */
export async function waitForUpdate({
  initiateUpdate,
  isComplete,
  initialMessage = 'Applying update...',
  noWaitSuccessMessage = 'Update being applied.',
  updateMessage = (isCompleted, runtime) =>
    `${isCompleted.status} (${Math.round(runtime / 1000)}s)`,
  waitSuccessMessage = (isCompleted, runtime) =>
    `Update completed in ${Math.round(
      runtime / 1000
    )}s with final status: ${isCompleted.status}`,
  timeoutMessage = (isCompleted, runtime) =>
    `Timeout occurred in ${Math.round(
      runtime / 1000
    )}s with final status: ${isCompleted.status}`,
  errorMessage = (isCompleted, runtime) =>
    `Error occurred in ${Math.round(
      runtime / 1000
    )}s with final status: ${isCompleted.status}`,
  wait = false,
  timeout = 10 * 60 * 1000,
  pollInterval = 5000,
  maxConsecutiveWaitErrors = 3,
  state,
}: {
  initiateUpdate: () => Promise<any>;
  isComplete: () => Promise<WaitCompleted>;
  initialMessage?: string;
  noWaitSuccessMessage?: string;
  updateMessage?: (isCompleted: WaitCompleted, runtime: number) => string;
  waitSuccessMessage?: (isCompleted: WaitCompleted, runtime: number) => string;
  timeoutMessage?: (isCompleted: WaitCompleted, runtime: number) => string;
  errorMessage?: (isCompleted: WaitCompleted, runtime: number) => string;
  wait?: boolean;
  timeout?: number;
  pollInterval?: number;
  maxConsecutiveWaitErrors?: number;
  state: State;
}): Promise<boolean> {
  if (timeout <= 0 || pollInterval <= 0) {
    throw new Error('Timeout and polling interval must be positive.');
  }
  const indicatorId = createProgressIndicator({
    total: undefined,
    message: initialMessage,
    type: 'indeterminate',
    state,
  });
  try {
    await initiateUpdate();
    if (!wait) {
      stopProgressIndicator({
        id: indicatorId,
        message: noWaitSuccessMessage,
        status: 'success',
        state,
      });
      return true;
    }
    const start = Date.now();
    let runtime = 0;
    let errors = 0;
    let isCompleted = await isComplete();
    while (!isCompleted.isComplete && start + timeout > Date.now()) {
      try {
        await sleep(pollInterval);
        isCompleted = await isComplete();

        // reset errors after successful isComplete call
        errors = 0;

        runtime = Date.now() - start;
        updateProgressIndicator({
          id: indicatorId,
          message: updateMessage(isCompleted, runtime),
          state,
        });
      } catch (e) {
        if (++errors > maxConsecutiveWaitErrors) throw e;
        runtime = Date.now() - start;
        updateProgressIndicator({
          id: indicatorId,
          message: `${
            e.message
          } - retry ${errors}/${maxConsecutiveWaitErrors} (${Math.round(runtime / 1000)}s)`,
          state,
        });
      }
    }
    const isTimedOut = runtime >= timeout;
    stopProgressIndicator({
      id: indicatorId,
      message: (isCompleted.isError
        ? errorMessage
        : isTimedOut
          ? timeoutMessage
          : waitSuccessMessage)(isCompleted, runtime),
      status: isCompleted.isError ? 'fail' : isTimedOut ? 'warn' : 'success',
      state,
    });
    return !isTimedOut && !isCompleted.isError;
  } catch (e) {
    stopProgressIndicator({
      id: indicatorId,
      message: `Error: ${e.response?.data?.code || e} - ${
        e.response?.data?.message
      }`,
      status: 'fail',
      state,
    });
    return false;
  }
}
